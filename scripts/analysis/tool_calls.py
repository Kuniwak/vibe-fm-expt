#!/usr/bin/env python3
"""List what the agent actually ran in a run: tool inputs and the environment's outputs only.

Usage: python3 -I scripts/analysis/tool_calls.py runs/run-NN   (writes runs/run-NN/analysis/tool-calls.md)

Exploratory analysis 4 (analysis/exploratory-4-tried/rules.md). The agent's own words are left out on
purpose: assistant text blocks, thinking blocks, and AskUserQuestion / TodoWrite inputs are dropped, so a
reader can describe what was run without reading what the agent said about it. Kept:
  - every other tool_use (name, input) with its tool_result (the environment's output);
  - background-task notifications (they carry the output of commands the agent started in the background).
Human turns are dropped. Each call keeps its timestamp and a running number (T1, T2, ...).
Long outputs are cut at LIMIT characters with a marker that says how much was cut.
"""
import json
import pathlib
import sys

LIMIT = 30000
DROP_TOOLS = {"AskUserQuestion", "TodoWrite"}


def text_of(content):
    if isinstance(content, str):
        return content
    out = []
    for x in content or []:
        if isinstance(x, dict):
            if x.get("type") == "text":
                out.append(x.get("text", ""))
            elif x.get("type") == "image":
                out.append("[image]")
    return "\n".join(out)


def cut(s):
    if len(s) <= LIMIT:
        return s
    return s[:LIMIT] + f"\n[... {len(s) - LIMIT} more characters cut by tool_calls.py ...]"


def fence(s):
    ticks = "```"
    while ticks in s:
        ticks += "`"
    return f"{ticks}\n{s}\n{ticks}"


def main(run_dir):
    run = pathlib.Path(run_dir)
    files = sorted((run / "record" / "transcripts").glob("*.jsonl"))
    if len(files) != 1:
        sys.exit(f"expected one transcript in {run}/record/transcripts, found {len(files)}")
    calls, results, order, notes = {}, {}, [], []
    for line in files[0].open(encoding="utf-8"):
        try:
            d = json.loads(line)
        except json.JSONDecodeError:
            continue
        m = d.get("message") or {}
        c = m.get("content")
        ts = d.get("timestamp", "")
        if d.get("type") == "assistant" and isinstance(c, list):
            for x in c:
                if isinstance(x, dict) and x.get("type") == "tool_use" and x.get("name") not in DROP_TOOLS:
                    if x["id"] not in calls:
                        calls[x["id"]] = (ts, x.get("name"), x.get("input"))
                        order.append(("call", x["id"]))
        elif d.get("type") == "user":
            if isinstance(c, list):
                for x in c:
                    if isinstance(x, dict) and x.get("type") == "tool_result":
                        results[x.get("tool_use_id")] = (ts, text_of(x.get("content")), x.get("is_error", False))
            t = text_of(c) if c is not None else ""
            if "<task-notification>" in t:
                order.append(("note", len(notes)))
                notes.append((ts, t))
    lines = [f"# {run.name}: tool calls and outputs", "",
             "Generated by scripts/analysis/tool_calls.py. The agent's own text is not included.", ""]
    n = 0
    for kind, key in order:
        if kind == "note":
            ts, t = notes[key]
            lines += [f"## background-task notification ({ts})", "", fence(cut(t)), ""]
            continue
        n += 1
        ts, name, inp = calls[key]
        lines += [f"## T{n} {name} ({ts})", "", "input:", "",
                  fence(cut(json.dumps(inp, ensure_ascii=False, indent=1))), ""]
        if key in results:
            rts, out, err = results[key]
            lines += [f"output ({rts}{', is_error' if err else ''}):", "", fence(cut(out)), ""]
        else:
            lines += ["output: none recorded", ""]
    dest = run / "analysis" / "tool-calls.md"
    dest.write_text("\n".join(lines), encoding="utf-8")
    print(dest, n, "calls,", len(notes), "notifications")


if __name__ == "__main__":
    main(sys.argv[1])
